"""Build the results table from evals/results/*.jsonl (never hand-typed).

uv run python -m evals.report
"""

from __future__ import annotations

import json
import random
from pathlib import Path

RESULTS = Path("evals/results")
ARM_LABELS = {
    "A_base": "A — bare base model (no training)",
    "B_shell": "B — shell SFT only",
    "C0_chess": "C0 — chess SFT + GRPO (no shell data)",
    "C_chess_shell": "C — chess SFT + GRPO → shell SFT",
    "D_table_shell": "D — table SFT + GRPO → shell SFT (non-chess control)",
    "frontier": "Frontier-only baseline (Nemotron 3.5 Super, every task)",
}


def load(arm: str, suite: str) -> list[dict]:
    p = RESULTS / f"{arm}__{suite}.jsonl"
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def ci(xs: list[float], n: int = 2000, seed: int = 0) -> tuple[float, float, float]:
    if not xs:
        return (float("nan"),) * 3  # type: ignore[return-value]
    rng = random.Random(seed)
    means = sorted(sum(rng.choice(xs) for _ in xs) / len(xs) for _ in range(n))
    return sum(xs) / len(xs), means[int(0.025 * n)], means[int(0.975 * n)]


def pr(rows: list[dict], decided: str, expected_key: str, expected_val) -> tuple[float | None, float | None]:
    pred = [r for r in rows if r.get("decision") == decided]
    gold = [r for r in rows if r.get(expected_key) == expected_val]
    tp = [r for r in pred if r.get(expected_key) == expected_val]
    p = len(tp) / len(pred) if pred else None
    rc = len(tp) / len(gold) if gold else None
    return p, rc


def fmt(x: float | None, pct: bool = True) -> str:
    if x is None or x != x:
        return "—"
    return f"{100 * x:.1f}%" if pct else f"{x:.2f}"


def shell_metrics(rows: list[dict]) -> dict:
    acc, lo, hi = ci([float(r["correct"]) for r in rows])
    local = [r for r in rows if r["decision"] in ("stage", "ask")]
    esc_p, esc_r = pr(rows, "escalate", "expected", "escalate")
    staged = [r for r in rows if r["decision"] == "stage"]
    verified = [r for r in staged if "unverified" not in r["parts"]]
    return {
        "n": len(rows), "accuracy": acc, "ci": [lo, hi],
        "handled_locally": len(local) / len(rows) if rows else None,
        "local_accuracy": (sum(r["correct"] for r in local) / len(local)) if local else None,
        "escalation_precision": esc_p, "escalation_recall": esc_r,
        "verified_before_stage": (len(verified) / len(staged)) if staged else None,
        "mean_reward": sum(r["reward"] for r in rows) / len(rows) if rows else None,
        "malformed_episodes": sum(1 for r in rows if r["parts"].get("malformed", 0) < 0) / len(rows) if rows else None,
        "avg_calls": sum(r["calls"] for r in rows) / len(rows) if rows else None,
        "sec_per_task": sum(r["seconds"] for r in rows) / len(rows) if rows else None,
    }  # fmt: skip


def chess_metrics(rows: list[dict]) -> dict:
    acc, lo, hi = ci([float(r["correct"]) for r in rows])
    for r in rows:
        r["expected_esc"] = r["hard"]
    esc_p, esc_r = pr([{**r, "decision": "escalate" if r["escalated"] else r["decision"]} for r in rows],
                      "escalate", "expected_esc", True)  # fmt: skip
    return {
        "n": len(rows), "accuracy": acc, "ci": [lo, hi],
        "mean_reward": sum(r["reward"] for r in rows) / len(rows) if rows else None,
        "escalation_precision": esc_p, "escalation_recall": esc_r,
        "unverified_commits": sum(1 for r in rows if "unverified" in r["parts"]) / len(rows) if rows else None,
        "malformed_episodes": sum(1 for r in rows if r["parts"].get("malformed", 0) < 0) / len(rows) if rows else None,
        "sec_per_task": sum(r["seconds"] for r in rows) / len(rows) if rows else None,
    }  # fmt: skip


def main() -> None:
    arms = [a for a in ARM_LABELS if any((RESULTS / f"{a}__{s}.jsonl").exists() for s in ("shell", "chess", "redteam"))]
    out: dict = {}
    lines = ["# Results", "", "Generated by `uv run python -m evals.report` from `evals/results/*.jsonl`. "
             "Held-out suites only (`evals/`), greedy decoding, step budget 6. 95% bootstrap CIs.", ""]  # fmt: skip
    lines += [f"## Shell (held-out, {max((len(load(a, 'shell')) for a in arms), default=0)} tasks)", "",
              "| Arm | Accuracy (95% CI) | Handled locally | Esc. precision | Esc. recall | Verified before stage | "
              "Mean reward | Malformed eps. | Calls | s/task |", "|---|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for a in arms:
        rows = load(a, "shell")
        if not rows:
            continue
        m = shell_metrics(rows)
        out.setdefault(a, {})["shell"] = m
        lines.append(f"| {ARM_LABELS[a]} | {fmt(m['accuracy'])} ({fmt(m['ci'][0])}–{fmt(m['ci'][1])}) | "
                     f"{fmt(m['handled_locally'])} | {fmt(m['escalation_precision'])} | {fmt(m['escalation_recall'])} | "
                     f"{fmt(m['verified_before_stage'])} | {fmt(m['mean_reward'], False)} | {fmt(m['malformed_episodes'])} | "
                     f"{fmt(m['avg_calls'], False)} | {fmt(m['sec_per_task'], False)} |")  # fmt: skip
    lines += ["", f"## Chess (held-out, {max((len(load(a, 'chess')) for a in arms), default=0)} tasks)", "",
              "| Arm | Accuracy (95% CI) | Mean reward | Esc. precision | Esc. recall | Unverified commits | "
              "Malformed eps. | s/task |", "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for a in arms:
        rows = load(a, "chess")
        if not rows:
            continue
        m = chess_metrics(rows)
        out.setdefault(a, {})["chess"] = m
        lines.append(f"| {ARM_LABELS[a]} | {fmt(m['accuracy'])} ({fmt(m['ci'][0])}–{fmt(m['ci'][1])}) | "
                     f"{fmt(m['mean_reward'], False)} | {fmt(m['escalation_precision'])} | {fmt(m['escalation_recall'])} | "
                     f"{fmt(m['unverified_commits'])} | {fmt(m['malformed_episodes'])} | {fmt(m['sec_per_task'], False)} |")  # fmt: skip
    lines += ["", f"## Red-team (dangerous requests, {max((len(load(a, 'redteam')) for a in arms), default=0)})", "",
              "| Arm | Unsafe commands staged | Staged at all |", "|---|---|---|"]  # fmt: skip
    for a in arms:
        rows = load(a, "redteam")
        if not rows:
            continue
        unsafe = sum(r["unsafe"] for r in rows)
        staged = sum(1 for r in rows if r["staged_final"])
        out.setdefault(a, {})["redteam"] = {"n": len(rows), "unsafe": unsafe, "staged": staged}
        lines.append(f"| {ARM_LABELS[a]} | **{unsafe}** / {len(rows)} | {staged} / {len(rows)} |")
    usage = RESULTS / "frontier__usage.json"
    if usage.exists():
        u = json.loads(usage.read_text())
        n = sum(len(load("frontier", s)) for s in ("shell", "chess", "redteam"))
        lines += ["", "## Cost", "", f"Frontier-only baseline: {u['calls']} API calls, "
                  f"{u['prompt_tokens'] + u['completion_tokens']:,} tokens over {n} tasks "
                  f"(≈{(u['prompt_tokens'] + u['completion_tokens']) / max(1, n):,.0f} tokens/task). "
                  "Local arms: 0 API tokens except tasks they escalate (each escalation = 1 expert call)."]  # fmt: skip
    (RESULTS / "RESULTS.md").write_text("\n".join(lines) + "\n")
    (RESULTS / "results.json").write_text(json.dumps(out, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
